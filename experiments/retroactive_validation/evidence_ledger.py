"""Evidence ledger: synthesis of the counted analyses (2 and 4).

Replaces the former category-by-analysis convergence table. That table needed a
per-category value from every source, which the verified data no longer supply
(see `published_data.py`, rule 2). The ledger instead records one entry per
finding, with the basis it rests on, and counts findings by direction. No
convergence ratio or binomial test is computed: findings with different bases
and measures are not exchangeable draws.

The paper quotes the ledger rather than restating it: `write_latex_counts`
emits the counts as `\\newcommand` macros for the paper to `\\input`.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Dict, List, Optional

# Direction of a finding relative to the analysis prediction
SUPPORT = "support"
AGAINST = "against"
MIXED = "mixed"
UNINFORMATIVE = "uninformative"
DIRECTIONS = [SUPPORT, MIXED, AGAINST, UNINFORMATIVE]

# What the finding rests on
NUMERIC_TEST = "numeric test"            # inferential statistic on verified values
NUMERIC_DESCRIPTIVE = "numeric descriptive"  # verified values compared, no test
QUALITATIVE = "qualitative"              # direction stated by the source, no values
BASES = [NUMERIC_TEST, NUMERIC_DESCRIPTIVE, QUALITATIVE]


def finding(
    analysis: str,
    source: str,
    claim: str,
    direction: str,
    basis: str,
    source_location: str,
    detail: Optional[Dict] = None,
) -> Dict:
    """Build one ledger entry."""
    assert direction in DIRECTIONS, direction
    assert basis in BASES, basis
    return {
        "analysis": analysis,
        "source": source,
        "claim": claim,
        "direction": direction,
        "basis": basis,
        "source_location": source_location,
        "detail": detail or {},
    }


def summarise(analyses: Dict[str, Dict]) -> Dict:
    """Collect findings from every analysis and count them by direction and basis."""
    findings: List[Dict] = []
    for result in analyses.values():
        findings.extend(result.get("findings", []))

    by_analysis = {}
    for name, result in analyses.items():
        fs = result.get("findings", [])
        by_analysis[name] = {
            "status": result.get("status", "run"),
            "n_findings": len(fs),
            "by_direction": {d: sum(f["direction"] == d for f in fs) for d in DIRECTIONS},
            "sources": sorted({f["source"] for f in fs}),
        }

    cross = Counter((f["direction"], f["basis"]) for f in findings)
    return {
        "experiment": "EvidenceLedger",
        "findings": findings,
        "by_analysis": by_analysis,
        "by_direction_and_basis": {
            d: {b: cross[(d, b)] for b in BASES} for d in DIRECTIONS
        },
        "n_findings": len(findings),
        "n_distinct_sources": len({f["source"] for f in findings}),
        "note": ("Counts of findings, not of independent tests. A source can "
                 "contribute more than one finding, and to more than one analysis."),
    }


def summary_line(summary: Dict) -> str:
    """The headline counts, in the form the paper reports them."""
    d = {k: sum(row.values()) for k, row in summary["by_direction_and_basis"].items()}
    b = {k: sum(row[k] for row in summary["by_direction_and_basis"].values()) for k in BASES}
    return (f"sources = {summary['n_distinct_sources']}     "
            f"findings = {summary['n_findings']}\n"
            "directions : " + ", ".join(f"{k} {v}" for k, v in d.items()) + "\n"
            "bases      : " + ", ".join(f"{k} {v}" for k, v in b.items()))


_WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight",
          "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen",
          "sixteen", "seventeen", "eighteen", "nineteen", "twenty"]


def _macro_name(label: str) -> str:
    return "Ledger" + "".join(w.capitalize() for w in label.split())


def latex_counts(summary: Dict) -> str:
    """`\\newcommand` block with every headline count, as digits and as a word.

    `\\LedgerSources` -> 7, `\\LedgerSourcesWord` -> seven, and likewise for
    Findings, each direction (`\\LedgerSupport`, ...) and each basis
    (`\\LedgerNumericTest`, ...).
    """
    counts = {"sources": summary["n_distinct_sources"], "findings": summary["n_findings"]}
    for d, row in summary["by_direction_and_basis"].items():
        counts[d] = sum(row.values())
    for b in BASES:
        counts[b] = sum(row[b] for row in summary["by_direction_and_basis"].values())

    lines = ["% Generated by experiments/retroactive_validation/evidence_ledger.py.",
             "% Do not edit: re-run `python -m experiments.retroactive_validation.run_all`.",
             "%"]
    lines += [f"% {s}" for s in summary_line(summary).splitlines()]
    for label, n in counts.items():
        name = _macro_name(label)
        lines.append(f"\\newcommand{{\\{name}}}{{{n}}}")
        lines.append(f"\\newcommand{{\\{name}Word}}{{{_WORDS[n] if n < len(_WORDS) else n}}}")
    return "\n".join(lines) + "\n"


def write_latex_counts(summary: Dict, output_dir: Path) -> Path:
    path = output_dir / "ledger_counts.tex"
    path.write_text(latex_counts(summary), encoding="utf-8")
    return path
